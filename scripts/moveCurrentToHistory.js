// moveCurrentToHistory.js
// Moves events from scrapedGenshinEvents.js to scrapedGenshinHistoryEvents.js
// and clears scrapedGenshinEvents.js

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const currentEventsPath = path.join(__dirname, '..', 'src', 'data', 'scrapedGenshinEvents.js');
const historyEventsPath = path.join(__dirname, '..', 'src', 'data', 'scrapedGenshinHistoryEvents.js');
const historyJsonPath = path.join(__dirname, '..', 'src', 'data', 'scrapedGenshinHistoryEvents.json');

console.log('Moving current events to history...\n');

// Import both files
const { scrapedGenshinEvents } = await import(`file://${currentEventsPath}?t=${Date.now()}`);
const { scrapedGenshinHistoryEvents } = await import(`file://${historyEventsPath}?t=${Date.now()}`);

console.log(`Current events: ${scrapedGenshinEvents.length}`);
console.log(`History events: ${scrapedGenshinHistoryEvents.length}`);

// Merge arrays - history events first, then current events
const mergedEvents = [...scrapedGenshinHistoryEvents, ...scrapedGenshinEvents];

// Deduplicate by title + start date - keep the LAST occurrence (current events override history)
const eventsMap = new Map();
for (const event of mergedEvents) {
  const key = `${event.title}|${new Date(event.start).toISOString()}`;
  eventsMap.set(key, event);
}

const uniqueEvents = Array.from(eventsMap.values());

console.log(`After deduplication: ${uniqueEvents.length} events\n`);

// Sort by start date
uniqueEvents.sort((a, b) => new Date(a.start).getTime() - new Date(b.start).getTime());

// Generate JS code for history file
const jsCode = `// scrapedGenshinHistoryEvents.js
// Auto-generated by scrapeGenshinHistory.js
// Last updated: ${new Date().toISOString()}

export const scrapedGenshinHistoryEvents = [
${uniqueEvents.map(event => `  {
    title: '${event.title.replace(/'/g, "\\'")}',
    start: new Date('${new Date(event.start).toISOString()}'),
    end: new Date('${new Date(event.end).toISOString()}'),
    image: '${(event.image || '').replace(/'/g, "\\'")}',
    description: \`${(event.description || '').replace(/`/g, '\\`').replace(/\$/g, '\\$')}\`,
    game: 'Genshin Impact',${event.wikiUrl ? `\n    wikiUrl: '${event.wikiUrl.replace(/'/g, "\\'")}',` : ''}${event.endNote ? `\n    endNote: '${event.endNote}',` : ''}
  }`).join(',  ')}
];
`;

// Write updated history file
fs.writeFileSync(historyEventsPath, jsCode);
console.log(`✅ Updated history file: ${uniqueEvents.length} events`);

// Generate JSON backup
const jsonData = uniqueEvents.map(event => ({
  title: event.title,
  start: new Date(event.start).toISOString(),
  end: new Date(event.end).toISOString(),
  image: event.image || '',
  description: event.description || '',
  game: 'Genshin Impact',
  ...(event.wikiUrl && { wikiUrl: event.wikiUrl }),
  ...(event.endNote && { endNote: event.endNote })
}));

fs.writeFileSync(historyJsonPath, JSON.stringify(jsonData, null, 2));
console.log(`💾 Updated JSON backup: ${historyJsonPath}`);

// Clear current events file
const emptyJsCode = `// scrapedGenshinEvents.js
// Auto-generated by scrapeGenshinCurrentUpcoming.js
// Last updated: ${new Date().toISOString()}

export const scrapedGenshinEvents = [
];
`;

fs.writeFileSync(currentEventsPath, emptyJsCode);
console.log(`🗑️  Cleared current events file\n`);

console.log('✅ Done! All events moved to history.');

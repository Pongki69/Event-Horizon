// mergeIndefiniteEvents.js
// Merge Indefinite events into scrapedZZZHistoryEvents

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

console.log('\n🔄 Merging Indefinite events into ZZZ history...\n');

// Read Indefinite events
const indefinitePath = path.join(__dirname, 'zzz-indefinite-events.json');
const indefiniteEvents = JSON.parse(fs.readFileSync(indefinitePath, 'utf8'));

console.log(`📋 Found ${indefiniteEvents.length} Indefinite events to merge\n`);

// Read existing history events
const historyJsPath = path.join(__dirname, '..', 'src', 'data', 'scrapedZZZHistoryEvents.js');
const historyJsonPath = path.join(__dirname, '..', 'src', 'data', 'scrapedZZZHistoryEvents.json');

let existingEvents = [];
try {
  existingEvents = JSON.parse(fs.readFileSync(historyJsonPath, 'utf8'));
  console.log(`📊 Existing history events: ${existingEvents.length}\n`);
} catch (error) {
  console.log(`⚠️  Could not read existing history: ${error.message}\n`);
}

// Convert Indefinite events to the correct format
const formattedIndefiniteEvents = indefiniteEvents.map(event => ({
  title: event.name,
  start: new Date(event.startDate).toISOString(),
  end: 'Indefinite',
  endNote: 'Permanent',
  timezone: event.timezone,
  image: event.localImage,
  description: event.description,
  game: 'Zenless Zone Zero',
  wikiUrl: event.eventUrl
}));

// Remove any existing Indefinite events from history (to avoid duplicates)
const nonIndefiniteEvents = existingEvents.filter(e => e.end !== 'Indefinite');
console.log(`🗑️  Removed ${existingEvents.length - nonIndefiniteEvents.length} old Indefinite events\n`);

// Merge: non-Indefinite events + new Indefinite events
const mergedEvents = [...nonIndefiniteEvents, ...formattedIndefiniteEvents];

// Sort by start date (newest first)
mergedEvents.sort((a, b) => {
  const dateA = new Date(a.start);
  const dateB = new Date(b.start);
  return dateB - dateA;
});

console.log(`✅ Total merged events: ${mergedEvents.length}\n`);

// Generate JS file
const jsCode = `// scrapedZZZHistoryEvents.js
// Auto-generated by scrapeZZZHistory.js
// Last updated: ${new Date().toISOString()}

export const scrapedZZZHistoryEvents = [
${mergedEvents.map(event => {
  const endValue = event.end === 'Indefinite' ? `'Indefinite'` : `new Date('${event.end}')`;
  const endNoteField = event.endNote ? `\n    endNote: '${event.endNote}',` : '';
  
  return `  {
    title: '${event.title.replace(/'/g, "\\'")}',
    start: new Date('${event.start}'),
    end: ${endValue},${endNoteField}
    timezone: '${event.timezone}',
    image: '${event.image.replace(/'/g, "\\'")}',
    description: \`${event.description.replace(/`/g, '\\`').replace(/\$/g, '\\$')}\`,
    game: 'Zenless Zone Zero',${event.wikiUrl ? `\n    wikiUrl: '${event.wikiUrl.replace(/'/g, "\\'")}',` : ''}
  }`;
}).join(',\n')}
];
`;

fs.writeFileSync(historyJsPath, jsCode);
console.log(`✅ Updated: ${historyJsPath}\n`);

// Save JSON backup
fs.writeFileSync(historyJsonPath, JSON.stringify(mergedEvents, null, 2));
console.log(`✅ Updated: ${historyJsonPath}\n`);

console.log('🎉 Merge complete!\n');

// removeDuplicates.js
// Remove duplicate events from Genshin Impact data files

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

console.log('Removing duplicates from Genshin Impact data...\n');

// Load JS file
const jsPath = path.join(__dirname, '..', 'src', 'data', 'scrapedGenshinHistoryEvents.js');
const { scrapedGenshinHistoryEvents } = await import(`file://${jsPath}?t=${Date.now()}`);

console.log(`Original JS file: ${scrapedGenshinHistoryEvents.length} events\n`);

// Create map to track unique events
const eventsMap = new Map();

scrapedGenshinHistoryEvents.forEach(event => {
  const key = `${event.title}|||${new Date(event.start).toISOString()}`;
  eventsMap.set(key, event);
});

console.log(`After removing exact duplicates: ${eventsMap.size} events\n`);

// Remove colon variant duplicates (keep longer titles)
const allEvents = Array.from(eventsMap.values());
const keysToRemove = new Set();

for (let i = 0; i < allEvents.length; i++) {
  for (let j = i + 1; j < allEvents.length; j++) {
    const event1 = allEvents[i];
    const event2 = allEvents[j];
    
    // Check if they have the same start date
    if (new Date(event1.start).getTime() === new Date(event2.start).getTime()) {
      const title1 = event1.title;
      const title2 = event2.title;
      
      // Check if one title is a prefix of the other (before a colon)
      const baseTitle1 = title1.split(':')[0].trim();
      const baseTitle2 = title2.split(':')[0].trim();
      
      if (baseTitle1 === baseTitle2 && title1 !== title2) {
        // Keep the longer title (more specific)
        const keyToRemove = title1.length < title2.length 
          ? `${title1}|||${new Date(event1.start).toISOString()}`
          : `${title2}|||${new Date(event2.start).toISOString()}`;
        keysToRemove.add(keyToRemove);
        console.log(`Removing: "${title1.length < title2.length ? title1 : title2}"`);
        console.log(`Keeping:  "${title1.length < title2.length ? title2 : title1}"\n`);
      }
    }
  }
}

// Remove the shorter duplicates
keysToRemove.forEach(key => eventsMap.delete(key));

console.log(`After removing colon variants: ${eventsMap.size} events\n`);

// Convert to array and sort by start date (newest first)
const cleanedEvents = Array.from(eventsMap.values())
  .sort((a, b) => new Date(b.start) - new Date(a.start));

// Generate JS code
const eventsCode = cleanedEvents.map(event => {
  const endNoteField = event.endNote ? `\n    endNote: '${event.endNote}',` : '';
  return `  {
    title: '${event.title.replace(/'/g, "\\'")}',
    start: new Date('${new Date(event.start).toISOString()}'),
    end: new Date('${new Date(event.end).toISOString()}'),${endNoteField}
    image: '${(event.image || '').replace(/'/g, "\\'")}',
    description: \`${(event.description || '').replace(/`/g, '\\`').replace(/\$/g, '\\$')}\`,
    game: 'Genshin Impact',
    wikiUrl: '${(event.wikiUrl || '').replace(/'/g, "\\'")}',
  }`;
}).join(',\n');

const jsCode = `// scrapedGenshinHistoryEvents.js
// Auto-generated by scrapeGenshinCurrentUpcoming.js
// Last updated: ${new Date().toISOString()}

export const scrapedGenshinHistoryEvents = [
${eventsCode}
];
`;

// Write JS file
fs.writeFileSync(jsPath, jsCode);
console.log(`✅ Updated JS file: ${cleanedEvents.length} events (removed ${scrapedGenshinHistoryEvents.length - cleanedEvents.length})\n`);

// Update JSON file
const jsonPath = path.join(__dirname, '..', 'src', 'data', 'scrapedGenshinHistoryEvents.json');
const jsonBackup = cleanedEvents.map(event => ({
  title: event.title,
  start: new Date(event.start).toISOString(),
  end: new Date(event.end).toISOString(),
  endNote: event.endNote,
  image: event.image || '',
  description: event.description || '',
  game: 'Genshin Impact',
  wikiUrl: event.wikiUrl || ''
}));

fs.writeFileSync(jsonPath, JSON.stringify(jsonBackup, null, 2));
console.log(`✅ Updated JSON file: ${jsonBackup.length} events\n`);

console.log('=== Summary ===');
console.log(`Removed ${scrapedGenshinHistoryEvents.length - cleanedEvents.length} duplicate events`);
console.log(`Final count: ${cleanedEvents.length} unique events`);
